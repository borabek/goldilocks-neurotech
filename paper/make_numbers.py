"""Write paper/numbers.tex and paper/table1.tex from the result files.

Every number in a table, and the headline numbers in the text, is a \\val{group}{item}{field} macro
defined here from a JSON path, so the paper cannot drift from the results. scripts/verify_claims.py
expands these macros and checks the rest of the text.

Usage: python paper/make_numbers.py
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / 'paper'
DS = ['boas', 'sleep_edf', 'dodh', 'hmc']
DS_NAME = {'boas': 'BOAS', 'sleep_edf': 'Sleep-EDF', 'dodh': 'DOD-H', 'hmc': 'HMC'}
MODEL_NAME = {'yasa': 'YASA', 'v2': 'v2', 'cnn': 'CNN', 'cnn_balanced': 'CNN, balanced'}


def load(p):
    return json.loads((ROOT / p).read_text())


def get(obj, path):
    for k in path.split('/'):
        obj = obj[int(k)] if isinstance(obj, list) else obj[k]
    return obj


def main():
    defs = {}

    def put(key, value, nd=3):
        defs[key] = f'{value:.{nd}f}' if isinstance(value, float) else str(value)

    bench = load('results/paper/benchmark.json')
    t = bench['table']
    for ds in DS:
        for m in t[ds]:
            for k in ['kappa', 'macro_f1', 'wake_f1', 'wake_recall', 'tst_error_minutes']:
                nd = 1 if k == 'tst_error_minutes' else 3
                put(f'{ds}@{m}@{k}', t[ds][m][k]['mean'], nd)
                put(f'{ds}@{m}@{k}_lo', t[ds][m][k]['ci95'][0], nd)
                put(f'{ds}@{m}@{k}_hi', t[ds][m][k]['ci95'][1], nd)
    for ds, r in bench['ranking']['datasets'].items():
        put(f'rank@{ds}@tau', r['kendall_tau_kappa'], 2)
        put(f'rank@{ds}@p', r['p_value'], 2)
        put(f'rank@{ds}@bestrank', r['boas_best_rank_here'], 0)

    for ds in ['dodh', 'hmc']:
        put(f'gain@{ds}@q75', load(f'results/external_{ds}/metrics.json')['gains']['gains']['q75'], 2)
    rx = load('results/paper/ranking_extended.json')
    put('rankx@all@models', len(rx['models']), 0)
    for ds, r in rx['ranking'].items():
        put(f'rankx@{ds}@tau', r['kendall_tau_kappa'], 2)
        put(f'rankx@{ds}@tau_lo', r['tau_ci95'][0], 2)
        put(f'rankx@{ds}@tau_hi', r['tau_ci95'][1], 2)
        put(f'rankx@{ds}@bestrank', r['boas_best_rank_here'], 0)
        put(f'rankx@{ds}@yasadiff', r['yasa_minus_best_headband_kappa']['mean_difference'], 3)
        put(f'rankx@{ds}@yasadiff_lo', r['yasa_minus_best_headband_kappa']['ci95'][0], 3)
        put(f'rankx@{ds}@yasadiff_hi', r['yasa_minus_best_headband_kappa']['ci95'][1], 3)
    for k, v in rx['five_seeds']['ranges'].items():
        put(f'seeds@{k}@min', v['min'], 3 if k == 'boas_kappa' else 2)
        put(f'seeds@{k}@max', v['max'], 3 if k == 'boas_kappa' else 2)
    bb = load('results/paper/bitbrain_attempt.json')
    put('bb@w@v2', bb['chosen_w_v2'], 1)
    for mask in ['all_scored', 'vendor_covered']:
        for m, s in bb['test'][mask].items():
            put(f'bb@{mask}@{m}', s['mean'])
            put(f'bb@{mask}@{m}_lo', s['ci95'][0])
            put(f'bb@{mask}@{m}_hi', s['ci95'][1])
    for k, s in bb['paired'].items():
        put(f'bb@paired@{k}', s['mean_difference'])
        put(f'bb@paired@{k}_lo', s['ci95'][0])
        put(f'bb@paired@{k}_hi', s['ci95'][1])

    lines = ['% Generated by paper/make_numbers.py from the result files. Do not edit by hand.',
             '\\makeatletter']
    for k in sorted(defs):
        lines.append(f'\\expandafter\\def\\csname val@{k}\\endcsname{{{defs[k]}}}')
    lines += ['\\makeatother',
              '\\newcommand{\\val}[3]{\\csname val@#1@#2@#3\\endcsname}']
    (OUT / 'numbers.tex').write_text('\n'.join(lines) + '\n')

    # Table 1
    rows = ['% Generated by paper/make_numbers.py. Do not edit by hand.',
            '\\begin{tabular}{llcccc}', '\\toprule',
            'Dataset & Model & Kappa & Macro-F1 & Wake F1 & Sleep-time error (min) \\\\', '\\midrule']
    for i, ds in enumerate(DS):
        for j, m in enumerate(bench['main_table_models']):
            cells = []
            for k in ['kappa', 'macro_f1', 'wake_f1', 'tst_error_minutes']:
                cells.append(f'\\val{{{ds}}}{{{m}}}{{{k}}} '
                             f'{{\\scriptsize[\\val{{{ds}}}{{{m}}}{{{k}_lo}}, \\val{{{ds}}}{{{m}}}{{{k}_hi}}]}}')
            name = DS_NAME[ds] if j == 0 else ''
            rows.append(f'{name} & {MODEL_NAME[m]} & ' + ' & '.join(cells) + ' \\\\')
        if i < len(DS) - 1:
            rows.append('\\midrule')
    rows += ['\\bottomrule', '\\end{tabular}']
    (OUT / 'table1.tex').write_text('\n'.join(rows) + '\n')
    print(len(defs), 'values written')


if __name__ == '__main__':
    main()
